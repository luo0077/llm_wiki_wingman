@dataclass
class ProjectContext:
    overview: Optional[str] = None
    schema: Optional[str] = None
    agent_workspace: str = ""


@dataclass
class AgentContextInput:
    query: str
    project: ProjectContext
    router: RouterDecision
    history: Sequence[AgentConversationMessage] = field(default_factory=list)
    skills: Sequence[AgentSkill] = field(default_factory=list)
    skill_mode: AgentSkillMode = AgentSkillMode.EXPLICIT
    references: Sequence[AgentReference] = field(default_factory=list)
    retrieval_summary: str = ""
    explicit_files: Sequence[Tuple[str, str]] = field(default_factory=list)


@dataclass
class BuiltAgentContext:
    system: str
    user: str


def load_project_context(project_path: str) -> ProjectContext:
    root = Path(project_path)
    return ProjectContext(
        overview=read_trimmed(root / "overview.md", MAX_OVERVIEW_CHARS)
        or read_trimmed(root / "wiki" / "overview.md", MAX_OVERVIEW_CHARS),
        schema=read_trimmed(root / "schema.md", MAX_SCHEMA_CHARS)
        or read_trimmed(root / "wiki" / "schema.md", MAX_SCHEMA_CHARS),
        agent_workspace=agent_workspace_display(root),
    )


def build_agent_context(input: AgentContextInput) -> BuiltAgentContext:
    return BuiltAgentContext(
        system=build_system_context(input.project, input.router, input.skills, input.skill_mode),
        user=build_user_context(input),
    )


def build_system_context(project: ProjectContext, router: RouterDecision,
                         skills: Sequence[AgentSkill], skill_mode: AgentSkillMode) -> str:
    out = "\n".join([
        "You are the LLM Wiki backend Agent.",
        "Answer using the current project context, available tools, and cited references.",
        "If evidence is insufficient, say what is missing instead of inventing facts.",
        "When using references, mention the relevant page paths naturally.",
        "Do not claim that internet or local-source search is unavailable when those tools are enabled; use the provided tool context and tool hints.",
    ])
    out += "\n\nTool policy:\n"
    out += "- wiki.search retrieves pages for factual or topical questions.\n"
    out += "- graph.search retrieves relationships, neighbors, backlinks, dependencies, and connections between project entities. Prefer it when the requested answer is about how concepts or entities relate, and use concise entity names rather than the full natural-language question.\n"
    if router.should_hint_web:
        out += "- web.search is available when current or external information is useful.\n"
    if router.should_hint_anytxt:
        out += "- anytxt.search is available for local or remote file content indexed by AnyTXT.\n"
    out += f"- Router hint: {_INTENT_DEBUG[QueryIntent(router.intent)]}. {router.rationale}\n"
    out += "\nGenerated file policy:\n"
    out += (
        "- All files generated by the Agent, skills, shell commands, scripts, image tools, HTML exports, or any "
        "future generation feature must be created under this visible project workspace: "
        f"{project.agent_workspace}.\n"
    )
    out += "- Do not create generated files in the user's home folder, Desktop, Downloads, system temp folders, hidden app metadata folders, or skill installation folders.\n"
    out += "- Treat skill folders as read-only instruction/reference sources. If a skill or script needs output files, pass or choose a path under the Agent workspace above.\n"
    out += "- If the requested visual can be represented as a Mermaid diagram, reply with a ```mermaid fenced code block directly instead of generating an HTML file just to display that diagram.\n"
    out += "- When using shell.exec, prefer relative output paths because the shell runs from the Agent workspace; use the LLM_WIKI_AGENT_WORKSPACE environment variable when an absolute output path is required.\n"

    if project.overview is not None and project.overview.strip():
        out += "\n\nProject overview:\n"
        out += trim_chars(project.overview, MAX_OVERVIEW_CHARS)
    if project.schema is not None and project.schema.strip():
        out += "\n\nProject schema:\n"
        out += trim_chars(project.schema, MAX_SCHEMA_CHARS)
    if skills:
        if AgentSkillMode.parse(skill_mode) == AgentSkillMode.AUTO:
            out += "\n\nThe following skills provide specialized instructions for specific tasks.\n"
            out += "Use a skill only when the latest request matches its description. To inspect a skill, use the listed SKILL.md location; when a skill references a relative path, resolve it against the skill directory.\n"
            out += render_available_skills(skills)
        else:
            out += "\n\nSelected skills:\n"
            out += "The user explicitly selected the following skill instructions for this turn. Treat them as task-specific instructions and apply them unless they conflict with safety, project boundaries, or the user's latest request. Supporting files should still be read lazily from the listed skill directory only when needed.\n"
            remaining = MAX_SKILL_CHARS
            for skill in skills:
                if remaining == 0:
                    break
                piece = trim_chars(render_explicit_skill(skill), remaining)
                remaining = max(0, remaining - len(piece))
                out += piece
                out += "\n"
    return out


def render_available_skills(skills: Sequence[AgentSkill]) -> str:
    out = "\n<available_skills>\n"
    rendered = 0
    for skill in list(skills)[:MAX_AUTO_SKILLS]:
        entry = (
            f"  <skill>\n    <name>{escape_xml(skill.name)}</name>\n"
            f"    <description>{escape_xml(skill.description.strip())}</description>\n"
            f"    <location>{escape_xml(skill.location)}</location>\n  </skill>\n"
        )
        if len(out) + len(entry) > MAX_AUTO_SKILL_INDEX_CHARS:
            break
        out += entry
        rendered += 1
    if rendered < len(skills):
        out += (
            f"  <omitted>{len(skills) - rendered} additional skill(s) omitted from the automatic index. "
            "Explicitly select a skill to include its full instructions.</omitted>\n"
        )
    out += "</available_skills>\n"
    return out


def render_explicit_skill(skill: AgentSkill) -> str:
    return (
        f"\n<skill name=\"{escape_xml(skill.name)}\" location=\"{escape_xml(skill.location)}\">\n"
        f"References are relative to {skill.base_dir}.\n\n{skill.instructions.strip()}\n</skill>"
    )


def build_user_context(input: AgentContextInput) -> str:
    out = ""
    if input.history:
        out += "Recent conversation history:\n"
        history = ""
        for item in list(input.history)[-12:]:
            history += f"{item.role}: {collapse_whitespace(item.content)}\n"
        out += trim_chars(history, MAX_HISTORY_CHARS)
        out += "\n\n"

    if input.explicit_files:
        out += "User-selected project files:\n"
        remaining = MAX_EXPLICIT_CONTEXT_CHARS
        for path, content in input.explicit_files:
            if remaining == 0:
                break
            prefix = f"\n<file path=\"{escape_xml(path)}\">\n"
            suffix = "\n</file>\n"
            overhead = len(prefix) + len(suffix)
            if remaining <= overhead:
                break
            body = trim_chars(escape_xml(content), remaining - overhead)
            out += prefix + body + suffix
            remaining = max(0, remaining - (overhead + len(body)))
        out += "\n\n"

    out += "Retrieved project context:\n"
    if not input.references:
        out += "No matching wiki references were found.\n\n"
    else:
        rendered = ""
        for idx, ref in enumerate(input.references):
            rendered += f"{idx + 1}. [{ref.kind}] {ref.title} ({ref.path})\n"
            if ref.snippet is not None:
                rendered += f"Snippet: {collapse_whitespace(ref.snippet)}\n"
            ctx = ref.knowledge_context
            if ctx is not None:
                if ctx.related_to:
                    rendered += f"Graph neighbors of: {', '.join(ctx.related_to)}\n"
                if ctx.tags:
                    rendered += f"Tags: {', '.join(ctx.tags)}\n"
                if ctx.outgoing_links:
                    rendered += f"Links to: {', '.join(ctx.outgoing_links)}\n"
                if ctx.backlinks:
                    rendered += f"Backlinks: {', '.join(ctx.backlinks)}\n"
                rendered += f"Related links: {ctx.link_count}\n"
                v = ctx.latest_version
                if v is not None:
                    rendered += f"Latest version: {v.author} via {v.tool} at {v.timestamp}\n"
        out += trim_chars(rendered, MAX_REFERENCE_CHARS)
        out += "\n"

    out += "Retrieval summary:\n"
    out += trim_chars(input.retrieval_summary, 8_000)
    out += "\n\nLatest user request:\n"
    out += input.query.strip()
    return out


def load_explicit_context_files(project_path: str, requested: Sequence[str]) -> List[Tuple[str, str]]:
    """Synchronous (blocking) port of the async Rust fn; call from a worker thread / run_in_threadpool."""
    from ..commands import fs as fs_cmds

    root = Path(project_path)
    try:
        root_canon = root.resolve(strict=True)
    except OSError:
        return []
    out: List[Tuple[str, str]] = []
    remaining = MAX_EXPLICIT_CONTEXT_CHARS
    for requested_path in list(requested)[:MAX_EXPLICIT_CONTEXT_FILES]:
        normalized = requested_path.strip().replace("\\", "/")
        if not normalized or normalized.startswith("/") or (len(normalized) > 1 and normalized[1] == ":"):
            continue
        parts = normalized.split("/")
        # Rust Path::components() drops empty and "." segments; ".." / prefixes are non-Normal.
        comps = [p for p in parts if p not in ("", ".")]
        if any(p == ".." for p in comps):
            continue
        if any(part.startswith(".") for part in parts):
            continue
        candidate = root / normalized
        try:
            cand_canon = candidate.resolve(strict=True)
        except OSError:
            continue
        try:
            cand_canon.relative_to(root_canon)
        except ValueError:
            continue
        if not cand_canon.is_file():
            continue
        try:
            content = fs_cmds.read_file(str(cand_canon), False)
        except Exception:
            continue
        fitted = trim_chars(content.strip(), min(remaining, MAX_EXPLICIT_FILE_CHARS))
        if not fitted:
            continue
        remaining = max(0, remaining - len(fitted))
        out.append((str(candidate).replace("\\", "/"), fitted))
        if remaining == 0:
            break
    return out


def read_trimmed(path, max_chars: int) -> Optional[str]:
    try:
        raw = Path(path).read_bytes().decode("utf-8")
    except (OSError, UnicodeDecodeError):
        return None
    t = raw.strip()
    if not t:
        return None
    return trim_chars(t, max_chars)


def trim_chars(value: str, max_chars: int) -> str:
    if len(value) <= max_chars:
        return value
    return value[: max(0, max_chars - 3)] + "..."


def collapse_whitespace(value: str) -> str:
    return " ".join(value.split())


def escape_xml(s: str) -> str:
    return (s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
            .replace('"', "&quot;").replace("'", "&apos;"))


def intent_label(intent: QueryIntent) -> str:
    return _INTENT_LABEL[QueryIntent(intent)]
